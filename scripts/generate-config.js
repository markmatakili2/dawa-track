const fs = require('fs');
const url = process.env.SUPABASE_URL || '';
const anonKey = process.env.SUPABASE_ANON_KEY || '';
const turnstileSiteKey = process.env.TURNSTILE_SITE_KEY || '';
if (!url || !anonKey) {
  console.warn('[generate-config] SUPABASE_URL / SUPABASE_ANON_KEY not set — config.js will be empty.');
}
const content = `// AUTO-GENERATED by scripts/generate-config.js at build time. Do not edit or commit.\nwindow.DAWA_SUPABASE_URL = ${JSON.stringify(url)};\nwindow.DAWA_SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)};\nwindow.DAWA_TURNSTILE_SITE_KEY = ${JSON.stringify(turnstileSiteKey)};\n`;
fs.writeFileSync('config.js', content);
console.log('[generate-config] config.js written.');
